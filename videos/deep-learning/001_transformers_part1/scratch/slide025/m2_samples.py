#!/usr/bin/env python3
"""Point sampler + fine region maps for slide_025.jpg (960x540)."""
import sys
import numpy as np
from PIL import Image

im = np.asarray(Image.open(sys.argv[1]).convert("RGB")).astype(int)

def sample(name, x, y, rad=2):
    patch = im[max(0,y-rad):y+rad+1, max(0,x-rad):x+rad+1].reshape(-1, 3)
    med = np.median(patch, axis=0).astype(int)
    print(f"{name:34s} ({x:3d},{y:3d}) -> #{med[0]:02X}{med[1]:02X}{med[2]:02X} {tuple(med)}")

