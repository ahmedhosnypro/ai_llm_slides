def fail(msg):
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def resolve_rel_id(rid, image_name, rels_xml, slide_xml):
    """Resolve the relationship id for an equation. Accepts rel_id directly,
    or an image filename matched against rel targets / pic descr attributes."""
    rel_targets = dict(re.findall(
        r'<Relationship Id="([^"]+)"[^>]*Target="([^"]+)"', rels_xml))
    if rid is None and image_name is None:
        fail("manifest equation needs 'rel_id' or 'image'")
    if rid is None:
        # 1) rel target basename
        matches = [r for r, tgt in rel_targets.items()
                   if os.path.basename(tgt) == image_name]
        if len(matches) > 1:
            fail(f"image {image_name!r} matches multiple rel ids: {matches}")
        if matches:
            rid = matches[0]
        else:
            # 2) pic descr attribute (pptxgenjs writes the source asset path)
            descrs = re.findall(r'descr="([^"]*)"', slide_xml)
            for d in descrs:
                if os.path.basename(d.replace("\\", "/")) == image_name:
                    m = re.findall(r'r:embed="([^"]+)"', slide_xml)
                    # match by position: find pic blocks containing this descr
                    for pm in re.finditer(
                            r"<p:pic(?:\s[^>]*)?>.*?</p:pic>", slide_xml, re.S):
                        if image_name in pm.group(0):
                            ids = re.findall(r'r:embed="([^"]+)"', pm.group(0))
                            if len(ids) != 1:
                                fail(f"pic with descr {image_name!r} has "
                                     f"{len(ids)} embeds")
                            rid = ids[0]
                            break
                    if rid:
                        break
        if rid is None:
            fail(f"cannot resolve image {image_name!r} to a relationship id")
    else:
        if rid not in rel_targets:
            fail(f"rel_id {rid!r} not found in slide rels")
        if image_name is not None and \
                os.path.basename(rel_targets[rid]) != image_name and \
                image_name not in slide_xml:
            # tolerate the pptxgenjs descr mismatch only when the descr mentions it
            descr_hit = False
            for pm in re.finditer(r"<p:pic(?:\s[^>]*)?>.*?</p:pic>", slide_xml, re.S):
                if f'r:embed="{rid}"' in pm.group(0) and image_name in pm.group(0):
                    descr_hit = True
            if not descr_hit:
                fail(f"rel_id {rid} target {rel_targets[rid]!r} does not match "
                     f"image {image_name!r}")
    return rid


def find_pic_block(slide_xml, rid):
    """Return (start, end, pic_xml) of the <p:pic> embedding rid, the string
    "ALREADY_WRAPPED" if the pic sits inside an mc:Fallback, or None if absent.
    Raises if rid appears but not exactly once."""
    fallback_spans = [(m.start(), m.end())
                      for m in re.finditer(r"<mc:Fallback>.*?</mc:Fallback>",
                                           slide_xml, re.S)]
    spans = [(m.start(), m.end(), m.group(0))
             for m in re.finditer(r"<p:pic(?:\s[^>]*)?>.*?</p:pic>",
                                  slide_xml, re.S)]
    hits = [s for s in spans if f'r:embed="{rid}"' in s[2]]
    # a pic nested inside an mc:Fallback is already wrapped — not a target
    hits = [s for s in hits
            if not any(fs <= s[0] and s[1] <= fe for fs, fe in fallback_spans)]
    if len(hits) == 1:
        return hits[0]
    if len(hits) > 1:
        fail(f"r:embed={rid!r} appears in {len(hits)} <p:pic> elements — "
             "ambiguous manifest")
    # zero bare pics: is it already inside a Fallback, or nowhere?
    if f'r:embed="{rid}"' in slide_xml:
        for fs, fe in fallback_spans:
            if f'r:embed="{rid}"' in slide_xml[fs:fe]:
                return "ALREADY_WRAPPED"
        fail(f"r:embed={rid!r} present in slide XML but no <p:pic> and no "
             "mc:Fallback found — refusing to touch it")
    return None


def pic_cnvpr_id(pic_xml):
    """The original pic's p:cNvPr id. PowerPoint reuses the SAME shape id in
    the Choice and the Fallback of an AlternateContent block (they are two
    representations of one shape) — see the banked real-Office sample."""
    m = re.search(r'<p:cNvPr id="(\d+)"', pic_xml)
    if not m:
        fail("targeted <p:pic> has no p:cNvPr id")
    return m.group(1)


def build_alternate_content(pic_xml, omml_para, label):
    """Build the mc:AlternateContent block: PowerPoint-pattern OMML Choice
    (same frame, same shape id) + original pic verbatim as Fallback.

    Choice structure mirrors the real Microsoft-authored sample and the
    converged generator patterns (evidence: qa/omml_v2/research/):
      - p:sp with the pic's cNvPr id and xfrm (frame preserved exactly)
      - txBody = bodyPr(zero-inset, ctr-anchored, noAutofit) + a:lstStyle
      - a:p = pPr(algn=ctr, buNone) + a14:m > oMathPara(jc=centerGroup)
        + a:endParaRPr
    """
    m = re.search(r"<a:xfrm>\s*<a:off x=\"(-?\d+)\" y=\"(-?\d+)\"/>\s*"
                  r"<a:ext cx=\"(\d+)\" cy=\"(\d+)\"/>\s*</a:xfrm>", pic_xml)
    if not m:
        fail("targeted <p:pic> has no a:xfrm a:off/a:ext — cannot mirror frame")
    off_x, off_y, ext_cx, ext_cy = m.groups()
    shape_id = pic_cnvpr_id(pic_xml)
    descr = _escape(label)
    return (
        "<mc:AlternateContent>"
        f'<mc:Choice xmlns:a14="{NS_A14}" Requires="a14">'
        "<p:sp><p:nvSpPr>"
        f'<p:cNvPr id="{shape_id}" name="Equation OMML" descr="{descr}"/>'
        '<p:cNvSpPr txBox="1"/><p:nvPr/>'
        "</p:nvSpPr><p:spPr>"
        f'<a:xfrm><a:off x="{off_x}" y="{off_y}"/>'
        f'<a:ext cx="{ext_cx}" cy="{ext_cy}"/></a:xfrm>'
        '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/>'
        "</p:spPr><p:txBody>"
        '<a:bodyPr lIns="0" tIns="0" rIns="0" bIns="0" anchor="ctr">'
        '<a:noAutofit/></a:bodyPr>'
        "<a:lstStyle/>"
        '<a:p><a:pPr algn="ctr"><a:buNone/></a:pPr>'
        f"<a14:m>{omml_para}</a14:m>"
        '<a:endParaRPr lang="en-US" dirty="0"/>'
        "</a:p></p:txBody></p:sp>"
        "</mc:Choice>"
        f"<mc:Fallback>{pic_xml}</mc:Fallback>"
        "</mc:AlternateContent>"
    )


def ensure_mc_ns(slide_xml):
    root = re.search(r"<p:sld(\s[^>]*)?>", slide_xml)
    if not root:
        fail("slide XML does not start with a <p:sld> element")
    tag = root.group(0)
    if "xmlns:mc=" in tag:
        return slide_xml
    new_tag = tag.replace("<p:sld", f'<p:sld xmlns:mc="{NS_MC}"', 1)
    return slide_xml[:root.start()] + new_tag + slide_xml[root.end():]


def wrap_slide(slide_xml, rels_xml, equations, log):
    """Apply all replacements for one slide. Returns new slide XML."""
    # Idempotency pre-check per equation happens inside the loop.
    n_wrapped = 0
    n_skipped = 0
    pending = list(equations)
    # Pre-resolve rel ids so failures abort before any mutation.
    resolved = []
    for eq in pending:
        rid = resolve_rel_id(eq.get("rel_id"), eq.get("image"),
                             rels_xml, slide_xml)
        resolved.append((rid, eq))

    for rid, eq in resolved:
        mathtext = eq.get("mathtext")
        if not mathtext:
            fail(f"equation for {rid} has no 'mathtext' source")
        hit = find_pic_block(slide_xml, rid)
        if hit == "ALREADY_WRAPPED":
            log(f"    {rid}: already wrapped in mc:AlternateContent — skipped")
            n_skipped += 1
            continue
        if hit is None:
            fail(f"no <p:pic> with r:embed={rid!r} in this slide — manifest "
                 "does not match the pptx")
        start, end, pic_xml = hit
        try:
            omml_para = mathtext_to_omml_para(
                mathtext, eq.get("font_size_pt", 18.0), eq.get("color", "#000000"))
        except MathParseError as e:
            fail(f"cannot convert mathtext for {rid} ({mathtext!r}): {e}")
        block = build_alternate_content(pic_xml, omml_para, mathtext)
        slide_xml = slide_xml[:start] + block + slide_xml[end:]
        n_wrapped += 1
        log(f"    {rid}: wrapped v2 ({len(omml_para)} bytes OMML-para, "
            f"mathtext={mathtext!r}, font={eq.get('font_size_pt')}pt, "
            f"color={eq.get('color')})")
    return slide_xml, n_wrapped, n_skipped


def main():
    ap = argparse.ArgumentParser(
        description="Wrap equation-image <p:pic> embeds in a pptx with "
                    "mc:AlternateContent (OMML Choice + original pic Fallback).")
    ap.add_argument("pptx", help="input pptx (never modified)")
    ap.add_argument("manifest", help="JSON manifest of equation embeds")
    ap.add_argument("-o", "--output", default=None,
                    help="output pptx (default: <input_stem>_omml.pptx next to input)")
    args = ap.parse_args()

    inp = args.pptx
    if not os.path.isfile(inp):
        fail(f"input pptx not found: {inp}")
    out = args.output
    if out is None:
        d, b = os.path.split(inp)
        out = os.path.join(d, os.path.splitext(b)[0] + "_omml.pptx")
    if os.path.abspath(out) == os.path.abspath(inp):
        fail("output path equals input path — refusing to overwrite the input")

    try:
        with open(args.manifest, "r", encoding="utf-8") as f:
            manifest = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        fail(f"cannot read manifest {args.manifest}: {e}")
    if "slides" not in manifest:
        fail("manifest has no 'slides' array")

    def log(msg):
        print(msg, file=sys.stderr)

    total_wrapped = 0
    total_skipped = 0
    modified = {}  # zip entry name -> new bytes

    try:
        zf = zipfile.ZipFile(inp, "r")
    except zipfile.BadZipFile as e:
        fail(f"not a valid zip/pptx: {e}")
    with zf:
        names = zf.namelist()
        for slide_entry in manifest["slides"]:
            try:
                snum = int(slide_entry["slide"])
            except (KeyError, TypeError, ValueError):
                fail(f"bad slide number in manifest: {slide_entry.get('slide')!r}")
            eqs = slide_entry.get("equations")
            if not eqs:
                fail(f"slide {snum}: manifest entry has no equations")
            part = f"ppt/slides/slide{snum}.xml"
            rels_part = f"ppt/slides/_rels/slide{snum}.xml.rels"
            if part not in names:
                fail(f"{part} not present in the pptx")
            if rels_part not in names:
                fail(f"{rels_part} not present in the pptx")
            slide_xml = zf.read(part).decode("utf-8")
            rels_xml = zf.read(rels_part).decode("utf-8")
            log(f"slide {snum}:")
            new_xml, n_wrapped, n_skipped = wrap_slide(
                slide_xml, rels_xml, eqs, log)
            if n_wrapped:
                new_xml = ensure_mc_ns(new_xml)
                try:
                    ET.fromstring(new_xml.encode("utf-8"))
                except ET.ParseError as e:
                    fail(f"slide {snum} XML failed well-formedness check after "
                         f"surgery: {e} — NO output written")
                modified[part] = new_xml.encode("utf-8")
            total_wrapped += n_wrapped
            total_skipped += n_skipped

        # Write the new zip: untouched entries byte-identical, modified ones replaced.
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zo:
            for item in zf.infolist():
                data = modified.get(item.filename)
                if data is None:
                    data = zf.read(item.filename)
                zo.writestr(item.filename, data)
    with open(out, "wb") as f:
        f.write(buf.getvalue())

    log(f"DONE: wrapped={total_wrapped} skipped_already_wrapped={total_skipped}")
    print(out)
    if total_wrapped == 0 and total_skipped == 0:
        fail("nothing was wrapped — manifest does not match this pptx")
    sys.exit(0)


if __name__ == "__main__":
    main()
