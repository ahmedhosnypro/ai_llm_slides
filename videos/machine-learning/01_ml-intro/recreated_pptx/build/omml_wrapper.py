class MathParseError(Exception):
    pass


class Tok:
    def __init__(self, kind, val):
        self.kind = kind  # 'cmd' | 'char' | 'space'
        self.val = val

    def __repr__(self):
        return f"<{self.kind}:{self.val!r}>"


def tokenize(src):
    toks = []
    i = 0
    n = len(src)
    while i < n:
        c = src[i]
        if c.isspace():
            i += 1  # mathtext ignores raw whitespace between tokens
            continue
        if c == "\\":
            if i + 1 >= n:
                raise MathParseError("trailing backslash")
            nxt = src[i + 1]
            if nxt.isalpha():
                j = i + 1
                while j < n and src[j].isalpha():
                    j += 1
                toks.append(Tok("cmd", src[i + 1:j]))
                i = j
            else:
                # \, \; \! \\ \% \# \$ \& \_ \{ \} — single-char commands
                toks.append(Tok("cmd", nxt))
                i += 2
            continue
        toks.append(Tok("char", c))
        i += 1
    return toks


# Node types: ('run', text, sty) with sty in {"i","p","b"} (italic math /
# plain upright / bold upright) | ('frac', num, den) | ('sqrt', deg, e)
#             ('nary', chr, sub, sup, e) | ('sub', base, sub) | ('sup', base, sup)
#             ('subsup', base, sub, sup) | ('bar', e) | ('acc', chr, e)
#             | ('delim', beg, end, e)  — each child is a node list.
# mathtext's "x{}_1" idiom (an empty {} group before a script, which kills the
# italic-correction tuck in the PNG) is parsed by re-attaching the script to
# the preceding node, so `x{}_1` and `x{}^T` yield ordinary sSub/sSup.

class Parser:
    def __init__(self, toks):
        self.toks = toks
        self.i = 0
        self.depth = 0  # brace nesting depth (drives n-ary operand extent)

    def peek(self):
        return self.toks[self.i] if self.i < len(self.toks) else None

    def next(self):
        t = self.peek()
        if t is None:
            raise MathParseError("unexpected end of mathtext")
        self.i += 1
        return t

    def parse(self):
        nodes = self.parse_seq(stop=None)
        if self.i != len(self.toks):
            raise MathParseError(
                f"unparsed tokens at {self.i}: {self.toks[self.i:self.i+3]}")
        return nodes

    def parse_seq(self, stop):
        """Parse until EOF or the stop token kind/val. Returns node list.
        stop is a predicate(tok)->bool for the NEXT unconsumed token."""
        nodes = []
        while True:
            t = self.peek()
            if t is None:
                if stop is not None:
                    raise MathParseError("unexpected end of mathtext inside group")
                return nodes
            if stop is not None and stop(t):
                return nodes
            atom = self.parse_atom_with_scripts()
            if (len(atom) == 1 and atom[0][0] in ("sub", "sup", "subsup")
                    and not atom[0][1]):
                # scripts attached to an empty {} group (the "x{}_1" idiom):
                # re-attach them to the preceding node as the base
                if not nodes:
                    raise MathParseError(
                        "scripts on an empty {} group with no preceding base")
                prev = nodes.pop()
                if prev[0] in ("sub", "sup", "subsup"):
                    raise MathParseError(
                        "scripts on an empty {} group after another script")
                nd = atom[0]
                nodes.append((nd[0], [prev]) + tuple(nd[2:]))
            else:
                nodes.extend(atom)

    def parse_group(self, what):
        t = self.next()
        if t.kind != "char" or t.val != "{":
            raise MathParseError(f"expected {{ for {what}, got {t!r}")
        self.depth += 1
        try:
            inner = self.parse_seq(stop=lambda tk: tk.kind == "char" and tk.val == "}")
        finally:
            self.depth -= 1
        self.next()  # consume }
        return inner

    def parse_arg(self, what):
        """A script/argument: {group} or a single token."""
        t = self.peek()
        if t is None:
            raise MathParseError(f"missing argument for {what}")
        if t.kind == "char" and t.val == "{":
            return self.parse_group(what)
        self.next()
        return self.parse_atom_from_token(t)

    def parse_atom_from_token(self, t):
        if t.kind == "cmd":
            return self.parse_command(t.val)
        return [("run", t.val, "i")]

    def parse_command(self, cmd):
        if cmd in ("frac", "dfrac", "tfrac"):
            num = self.parse_group("\\frac numerator")
            den = self.parse_group("\\frac denominator")
            return [("frac", num, den)]
        if cmd == "sqrt":
            deg = None
            t = self.peek()
            if t is not None and t.kind == "char" and t.val == "[":
                self.next()
                deg = self.parse_seq(stop=lambda tk: tk.kind == "char" and tk.val == "]")
                self.next()  # consume ]
            e = self.parse_group("\\sqrt radicand")
            return [("sqrt", deg, e)]
        if cmd in NARY:
            sub = None
            sup = None
            limloc = "undOvr"
            # mathtext idiom: \sum{}_{..}^{..} — the empty group keeps the large
            # display glyph but stacks the limits to its RIGHT (D upper, m=1
            # lower). Encode it as OMML limLoc="subSup"; plain \sum_{..}^{..}
            # stacks limits above/below -> "undOvr".
            t = self.peek()
            if (t is not None and t.kind == "char" and t.val == "{"
                    and self.i + 1 < len(self.toks)
                    and self.toks[self.i + 1].kind == "char"
                    and self.toks[self.i + 1].val == "}"):
                self.next()  # {
                self.next()  # }
                limloc = "subSup"
            # peek for scripts; the operand is the rest of the current expression
            while True:
                t = self.peek()
                if t is None:
                    break
                if t.kind == "char" and t.val == "_":
                    self.next()
                    sub = self.parse_arg(f"\\{cmd} sub")
                elif t.kind == "char" and t.val == "^":
                    self.next()
                    sup = self.parse_arg(f"\\{cmd} sup")
                else:
                    break
            # n-ary operand: everything that follows in the current expression
            # context (rest of the enclosing brace group, or the whole rest of
            # the top-level expression — matches how the PNG shows the summand)
            if self.depth == 0:
                e = self.parse_seq(stop=None)
            else:
                e = self.parse_seq(stop=lambda tk: tk.kind == "char" and tk.val == "}")
            return [("nary", NARY[cmd], sub, sup, e, limloc)]
        if cmd == "mathbb":
            inner = self.parse_group("\\mathbb")
            runs = []
            for kind, *rest in inner:
                if kind != "run":
                    raise MathParseError(
                        f"\\mathbb{{...}} may only contain letters, got {kind}")
                for ch in rest[0]:
                    if ch not in DOUBLE_STRUCK:
                        raise MathParseError(
                            f"\\mathbb has no double-struck glyph for {ch!r}")
                    runs.append(("run", DOUBLE_STRUCK[ch], "p"))
            if not runs:
                raise MathParseError("empty \\mathbb{...}")
            return runs
        if cmd == "mathbf":
            # mathtext renders \mathbf{...} as bold UPRIGHT letters
            inner = self.parse_group("\\mathbf")
            runs = []
            for kind, *rest in inner:
                if kind != "run":
                    raise MathParseError(
                        f"\\mathbf{{...}} may only contain letters/digits, "
                        f"got {kind}")
                for ch in rest[0]:
                    runs.append(("run", ch, "b"))
            if not runs:
                raise MathParseError("empty \\mathbf{...}")
            return runs
        if cmd in ("bar", "overline"):
            return [("bar", self.parse_group(f"\\{cmd}"))]
        if cmd == "hat":
            return [("acc", "\u005e", self.parse_arg("\\hat"))]
        if cmd == "vec":
            return [("acc", "\u20d7", self.parse_arg("\\vec"))]
        if cmd == "dot":
            return [("acc", "\u0307", self.parse_arg("\\dot"))]
        if cmd == "tilde":
            return [("acc", "~", self.parse_arg("\\tilde"))]
        if cmd in ("text", "mathrm"):
            inner = self.parse_group(f"\\{cmd}")
            runs = []
            for kind, *rest in inner:
                if kind == "run":
                    runs.append(("run", rest[0], "p"))
                else:
                    raise MathParseError(
                        f"\\{cmd}{{...}} may only contain plain text, got {kind}")
            if not runs:
                raise MathParseError(f"empty \\{cmd}{{...}}")
            return runs
        if cmd in FUNCTIONS:
            return [("run", cmd, "p")]
        if cmd in GREEK:
            return [("run", GREEK[cmd], "i")]
        if cmd in SYMBOLS:
            return [("run", SYMBOLS[cmd], "i")]
        if cmd == "left":
            beg = self.parse_delim_char("\\left")
            self.depth += 1
            try:
                content = self.parse_seq(
                    stop=lambda tk: tk.kind == "cmd" and tk.val == "right")
            finally:
                self.depth -= 1
            t = self.next()  # consume the \right command itself
            if t.kind != "cmd" or t.val != "right":
                raise MathParseError(f"internal: expected \\right, got {t!r}")
            end = self.parse_delim_char("\\right")
            return [("delim", beg, end, content)]
        raise MathParseError(f"unsupported mathtext command: \\{cmd}")

    def parse_delim_char(self, what):
        """The delimiter character token after \\left or \\right."""
        t = self.next()
        if t.kind == "char":
            if t.val in "()[]{}|.":
                return t.val
        elif t.kind == "cmd" and t.val == "langle":
            return "⟨"
        elif t.kind == "cmd" and t.val == "rangle":
            return "⟩"
        elif t.kind == "cmd" and t.val == "|":  # escaped \left\| norm bars
            return "|"
        raise MathParseError(f"unsupported delimiter after {what}: {t!r}")

    def parse_atom_with_scripts(self):
        t = self.next()
        if t.kind == "char" and t.val == "{":
            self.depth += 1
            try:
                inner = self.parse_seq(stop=lambda tk: tk.kind == "char" and tk.val == "}")
            finally:
                self.depth -= 1
            self.next()
            base = inner
        elif t.kind == "char" and t.val in "}_^":
            # bare '}' is consumed by group parsing, so reaching here is an error;
            # bare _ / ^ without a base is malformed. Literal ')'/']' are plain runs.
            raise MathParseError(f"unexpected {t.val!r} without a base")
        else:
            base = self.parse_atom_from_token(t)

        # trailing sub/superscripts
        sub = None
        sup = None
        while True:
            t = self.peek()
            if t is None:
                break
            if t.kind == "char" and t.val == "_":
                self.next()
                sub = self.parse_arg("subscript")
            elif t.kind == "char" and t.val == "^":
                self.next()
                sup = self.parse_arg("superscript")
            else:
                break
        if sub is not None and sup is not None:
            return [("subsup", base, sub, sup)]
        if sub is not None:
            return [("sub", base, sub)]
        if sup is not None:
            return [("sup", base, sup)]
        return base


_AMP = '&'  # ampersand char; kept non-entity in source


def _escape(s):
    """XML-escape text content / attribute values."""
    return (s.replace(_AMP, _AMP + 'amp;')
            .replace('<', _AMP + 'lt;')
            .replace('>', _AMP + 'gt;')
            .replace('"', _AMP + 'quot;'))


def emit(nodes, sz, color_hex, out):
    for nd in merge_runs(nodes):
        kind = nd[0]
        if kind == "run":
            _, text, sty = nd
            if sty not in ("i", "p", "b"):
                raise MathParseError(f"internal: unknown run style {sty!r}")
            out.append("<m:r>")
            if sty == "p":
                out.append('<m:rPr><m:sty m:val="p"/></m:rPr>')
                out.append(_run_rpr(sz, color_hex, italic=False))
            elif sty == "b":
                out.append('<m:rPr><m:sty m:val="b"/></m:rPr>')
                out.append(_run_rpr(sz, color_hex, italic=False, bold=True))
            else:
                out.append(_run_rpr(sz, color_hex, italic=True))
            out.append(f'<m:t xml:space="preserve">{_escape(text)}</m:t>')
            out.append("</m:r>")
        elif kind == "frac":
            out.append("<m:f>")
            out.append(f"<m:fPr>{_ctrl_pr(sz, color_hex)}</m:fPr>")
            out.append("<m:num>")
            emit(_require(nd[1], "m:num"), sz, color_hex, out)
            out.append("</m:num><m:den>")
            emit(_require(nd[2], "m:den"), sz, color_hex, out)
            out.append("</m:den></m:f>")
        elif kind == "sqrt":
            _, deg, e = nd
            if deg is None:
                out.append(f'<m:rad><m:radPr><m:degHide m:val="on"/>'
                           f'{_ctrl_pr(sz, color_hex)}</m:radPr>'
                           '<m:deg/><m:e>')
            else:
                out.append(f'<m:rad><m:radPr><m:degHide m:val="off"/>'
                           f'{_ctrl_pr(sz, color_hex)}</m:radPr><m:deg>')
                emit(_require(deg, "m:deg"), sz, color_hex, out)
                out.append('</m:deg><m:e>')
            emit(_require(e, "m:rad m:e"), sz, color_hex, out)
            out.append("</m:e></m:rad>")
        elif kind == "nary":
            _, ch, sub, sup, e, _lim = nd
            limloc = nd[5] if len(nd) > 5 else "undOvr"
            out.append('<m:nary><m:naryPr>'
                       f'<m:chr m:val="{ch}"/><m:limLoc m:val="{limloc}"/>'
                       f'{_ctrl_pr(sz, color_hex)}</m:naryPr>')
            out.append("<m:sub>")
            if sub is not None:
                emit(sub, sz, color_hex, out)
            out.append("</m:sub><m:sup>")
            if sup is not None:
                emit(sup, sz, color_hex, out)
            out.append("</m:sup><m:e>")
            emit(_require(e, "m:nary m:e"), sz, color_hex, out)
            out.append("</m:e></m:nary>")
        elif kind == "sub":
            out.append("<m:sSub>")
            out.append(f"<m:sSubPr>{_ctrl_pr(sz, color_hex)}</m:sSubPr><m:e>")
            emit(_require(nd[1], "m:sSub base"), sz, color_hex, out)
            out.append("</m:e><m:sub>")
            emit(_require(nd[2], "m:sSub sub"), sz, color_hex, out)
            out.append("</m:sub></m:sSub>")
        elif kind == "sup":
            out.append("<m:sSup>")
            out.append(f"<m:sSupPr>{_ctrl_pr(sz, color_hex)}</m:sSupPr><m:e>")
            emit(_require(nd[1], "m:sSup base"), sz, color_hex, out)
            out.append("</m:e><m:sup>")
            emit(_require(nd[2], "m:sSup sup"), sz, color_hex, out)
            out.append("</m:sup></m:sSup>")
        elif kind == "subsup":
            out.append("<m:sSubSup>")
            out.append(f"<m:sSubSupPr>{_ctrl_pr(sz, color_hex)}</m:sSubSupPr><m:e>")
            emit(_require(nd[1], "m:sSubSup base"), sz, color_hex, out)
            out.append("</m:e><m:sub>")
            emit(_require(nd[2], "m:sSubSup sub"), sz, color_hex, out)
            out.append("</m:sub><m:sup>")
            emit(_require(nd[3], "m:sSubSup sup"), sz, color_hex, out)
            out.append("</m:sup></m:sSubSup>")
        elif kind == "delim":
            _, beg, end, e = nd
            out.append("<m:d><m:dPr>")
            if beg != "(" or end != ")":
                out.append(f'<m:begChr m:val="{beg}"/><m:endChr m:val="{end}"/>')
            out.append(f"{_ctrl_pr(sz, color_hex)}</m:dPr><m:e>")
            emit(_require(e, "m:d m:e"), sz, color_hex, out)
            out.append("</m:e></m:d>")
        elif kind == "bar":
            out.append(f'<m:bar><m:barPr><m:pos m:val="top"/>'
                       f'{_ctrl_pr(sz, color_hex)}</m:barPr><m:e>')
            emit(_require(nd[1], "m:bar"), sz, color_hex, out)
            out.append("</m:e></m:bar>")
        elif kind == "acc":
            out.append(f'<m:acc><m:accPr><m:chr m:val="{nd[1]}"/>'
                       f'{_ctrl_pr(sz, color_hex)}</m:accPr><m:e>')
            emit(_require(nd[2], "m:acc"), sz, color_hex, out)
            out.append("</m:e></m:acc>")
        else:
            raise MathParseError(f"internal: unknown node kind {kind!r}")


# The math typeface every real PowerPoint slide-math run carries (byte-copied
# from the Microsoft-authored sample banked at qa/omml_v2/research/).
MATH_LATIN = ('<a:latin typeface="Cambria Math" panose="02040503050406030204" '
              'pitchFamily="18" charset="0"/>')


def _run_rpr(sz, color_hex, italic=True, bold=False):
    """The a:rPr every PowerPoint math run carries: lang/i/smtClean/sz, the
    baked solidFill color, and the Cambria Math latin typeface."""
    i_attr = "1" if italic else "0"
    b_attr = ' b="1"' if bold else ""
    return (f'<a:rPr lang="en-US" i="{i_attr}" smtClean="0" sz="{sz}"{b_attr}>'
            f'<a:solidFill><a:srgbClr val="{color_hex}"/></a:solidFill>'
            f'{MATH_LATIN}</a:rPr>')


def _ctrl_pr(sz, color_hex):
    """PowerPoint writes m:ctrlPr (with the same a:rPr) into every construct's
    property element (sSupPr, fPr, dPr, naryPr, radPr, barPr, accPr)."""
    return f'<m:ctrlPr>{_run_rpr(sz, color_hex, italic=True, bold=False)}</m:ctrlPr>'


def merge_runs(nodes):
    """Merge adjacent ('run', text, sty) nodes with the same style flag."""
    out = []
    for nd in nodes:
        if nd[0] == "run" and out and out[-1][0] == "run" and out[-1][2] == nd[2]:
            out[-1] = ("run", out[-1][1] + nd[1], nd[2])
        else:
            out.append(nd)
    return out


def _require(nodes, what):
    if not nodes:
        raise MathParseError(f"empty content for {what}")
    return nodes


def mathtext_to_omml(mathtext, font_size_pt, color_hex):
    """Convert a matplotlib-mathtext (LaTeX subset) string to an OMML
    <m:oMath>...</m:oMath> string with the given run size (pt) and color."""
    sz = int(round(float(font_size_pt) * 100))
    if sz <= 0:
        raise MathParseError(f"font_size_pt must be positive, got {font_size_pt!r}")
    color_hex = str(color_hex).lstrip("#").upper()
    if not re.fullmatch(r"[0-9A-F]{6}", color_hex):
        raise MathParseError(f"color must be a 6-digit hex string, got {color_hex!r}")
    toks = tokenize(mathtext)
    if not toks:
        raise MathParseError("empty mathtext")
    nodes = Parser(toks).parse()
    if not nodes:
        raise MathParseError(f"mathtext produced no content: {mathtext!r}")
    out = []
    emit(nodes, sz, color_hex, out)
    # xmlns:m on m:oMath itself mirrors the real Microsoft-authored sample
    # (banked at qa/omml_v2/research/real_office_sample/slide2.xml); the
    # a: namespace resolves from the slide root, exactly as in that sample.
    return f'<m:oMath xmlns:m="{NS_M}">' + "".join(out) + "</m:oMath>"


def mathtext_to_omml_para(mathtext, font_size_pt, color_hex):
    """The display/equation-only form PowerPoint writes for slide math:
    m:oMathPara > m:oMathParaPr(m:jc=centerGroup) > m:oMath. Per [MS-ODRAWXML]
    2.3.1 a14:m holds m:oMathPara (display) or m:oMath (inline); our equation
    textboxes are equation-only paragraphs, so the display form is the
    PowerPoint-idiomatic one (converged evidence: visualtex, genoffice, macro
    pptx_engine, ppt-master, flatmap-maker — see qa/omml_v2/research/).
    xmlns:m and xmlns:a are declared on the fragment root so the OMML block is
    self-contained (same mapping as the slide root; the macro pptx_engine
    declares them locally the same way)."""
    return (f'<m:oMathPara xmlns:m="{NS_M}" '
            f'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">'
            '<m:oMathParaPr><m:jc m:val="centerGroup"/></m:oMathParaPr>'
            + mathtext_to_omml(mathtext, font_size_pt, color_hex)
            + "</m:oMathPara>")


