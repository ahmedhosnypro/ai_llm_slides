const path = require("path");
const fs = require("fs");
const pptxgen = require("pptxgenjs");
const parent = require(path.resolve(__dirname, "components", "slide_004.js"));
const { drawHouseChrome } = require(path.resolve(__dirname, "..", "..", "shared_patterns", "house_chrome.js"));

const px = (v) => v / 72; // frame px -> inches

// ---- delta constants (frame px measurements) --------------------------------
const C = {
  ...parent.CHROME_CONSTS,
  EQ_BLUE: "0000CD",
  EQ_RED: "B22222",
  GREEN: "008000",
};

// purple projection (my frame): H dashed y274 x136..406; V dashed x402.5 y270..477
const PURPLE_H = { y: 274, x0: 136, x1: 406 };
const PURPLE_V = { x: 402.5, y0: 270, y1: 477 };
const PURPLE_DOTS = [
  [401.4, 275.6, 11],   // the point on the regression line
  [402.5, 473.2, 8.5],  // foot on the x-axis
];

// regression line: (172,436) -> (548,171.5)
const REGLINE = { x0: 172, y0: 436, x1: 548, y1: 171.5, width: 4 };

// box A = parent's Model box translated to (640,197), same 108x64
const BOX_A = { x: 640, y: 197, w: 108, h: 64 };
// box B (new): x643..833 y281..394
const BOX_B = { x: 643, y: 281, w: 191, h: 114 };

// L1 heading: per-run boxes at measured ink-left (avoids pptxgenjs's malformed
// mid-paragraph <a:pPr> between runs — LO's repair dropped runs in multi-run
// paragraphs; same absolute-position pattern as the equation PNG runs).
// Orig: 'Model' red 648..703, '( Line )' green 704..772 (pixel hue cores: parens
// classify GREEN), caps y285.5..300, underline rows 301..303.5 (per-run color).
const B_L1 = {
  y: 279, size: 21.5,
  parts: [
    { text: "Model", x: 648.5, color: C.EQ_RED },
    { text: "( Line )", x: 703.5, color: C.GREEN },
  ],
};
// L4 runs (orig: blue text 649..~797, ':' 795..796, 'a' red 800..809, ',' blue
// 814..816, 'b' red 820..830; caps y376.5..389.5)
const B_L4 = {
  y: 369.6, size: 20,
  parts: [
    { text: "Model Parameters : ", x: 648.5, color: C.EQ_BLUE },
    { text: "a", x: 799.5, color: C.EQ_RED },
    { text: ",", x: 814.5, color: C.EQ_BLUE },
    { text: "b", x: 819, color: C.EQ_RED },
  ],
};

// pen glyph
const PEN = { body: [569.5, 193.5, 577.5, 206.5], dot: [569, 192.5, 3.5] };

// rotated Weight label (my qzone): ink x116..124 (cap dir), y117..149 (text dir)
const WEIGHT = { cx: 120, cy: 133, size: 11, charSpacing: -0.3 };

const EQ = JSON.parse(fs.readFileSync(path.join(__dirname, "assets", "eq_s005_manifest.json"), "utf8"));

// ---- delta block draws ------------------------------------------------------

function drawRegressionLine(pptx, slide) {
  slide.addShape(pptx.ShapeType.line, {
    x: px(REGLINE.x0), y: px(REGLINE.y1),
    w: px(REGLINE.x1 - REGLINE.x0), h: px(REGLINE.y0 - REGLINE.y1),
    flipV: true, // start at bottom-left, end top-right
    line: { color: "000000", width: REGLINE.width },
  });
}

function drawPurpleDelta(pptx, slide) {
  const L = { color: C.PURPLE, width: 1.5, dashType: "dash" };
  slide.addShape(pptx.ShapeType.line, {
    x: px(PURPLE_H.x0), y: px(PURPLE_H.y), w: px(PURPLE_H.x1 - PURPLE_H.x0), h: 0,
    line: { ...L },
  });
  slide.addShape(pptx.ShapeType.line, {
    x: px(PURPLE_V.x), y: px(PURPLE_V.y0), w: 0, h: px(PURPLE_V.y1 - PURPLE_V.y0),
    line: { ...L },
  });
  for (const [cx, cy, d] of PURPLE_DOTS) {
    slide.addShape(pptx.ShapeType.ellipse, {
      x: px(cx - d / 2), y: px(cy - d / 2), w: px(d), h: px(d),
      fill: { color: C.PURPLE }, line: { type: "none" },
    });
  }
}

function drawModelBoxA(pptx, slide) {
  // parent's Model box styling (Arial bold 15, lineSpacing 18, FBFDE9/8F8BAB),
  // translated to this frame's measured position
  slide.addShape(pptx.ShapeType.rect, {
    x: px(BOX_A.x), y: px(BOX_A.y), w: px(BOX_A.w), h: px(BOX_A.h),
    fill: { color: C.MB_FILL }, line: { color: C.MB_BORDER, width: 0.75 },
  });
  slide.addText([
    { text: "Model", options: { color: C.RED, underline: { style: "sng" }, breakLine: true } },
    { text: "I/P:\u00A0\u00A0 Length", options: { color: "000000", breakLine: true } },
    { text: "O/P: Weight", options: { color: "000000" } },
  ], {
    x: px(BOX_A.x + 6.5), y: px(BOX_A.y + 4), w: px(98), h: px(58),
    align: "left", valign: "top", margin: 0,
    fontSize: 15, bold: true, fontFace: "Arial", lineSpacing: 18,
  });
}

function drawModelLineBox(pptx, slide) {
  slide.addShape(pptx.ShapeType.rect, {
    x: px(BOX_B.x), y: px(BOX_B.y), w: px(BOX_B.w), h: px(BOX_B.h),
    fill: { color: C.MB_FILL }, line: { color: C.MB_BORDER, width: 0.75 },
  });
  // L1 heading: per-run boxes (underline per-run color follows the run color)
  for (const part of B_L1.parts) {
    slide.addText(part.text, {
      x: px(part.x), y: px(B_L1.y), w: px(140), h: px(26),
      align: "left", valign: "top", margin: 0, underline: { style: "sng" },
      fontSize: B_L1.size, bold: true, italic: true, color: part.color,
      fontFace: "Times New Roman",
    });
  }
  // L2/L3 equation PNG runs (exact size, baseline-law placement from manifest)
  for (const line of ["L2", "L3"]) {
    for (const run of EQ.lines[line].runs) {
      slide.addImage({
        path: path.join(__dirname, "assets", run.image),
        x: run.x_in, y: run.y_in, w: run.w_in, h: run.h_in,
      });
    }
  }
  // L4 (after the measured blank-line gap): per-run boxes. The blue text carries
  // charSpacing -0.6 to hit the original's ':' position (Liberation Bold Italic runs
  // ~11px wider than the original's face over "Model Parameters : ").
  for (const part of B_L4.parts) {
    slide.addText(part.text, {
      x: px(part.x), y: px(B_L4.y), w: px(200), h: px(24),
      align: "left", valign: "top", margin: 0,
      fontSize: B_L4.size, bold: true, italic: true, color: part.color,
      fontFace: "Times New Roman",
      charSpacing: part.text.length > 2 ? -0.6 : 0,
    });
  }
}

function drawPenGlyph(pptx, slide) {
  const [x0, y0, x1, y1] = PEN.body;
  slide.addShape(pptx.ShapeType.line, {
    x: px(x0), y: px(y0), w: px(x1 - x0), h: px(y1 - y0),
    line: { color: "8A8A8A", width: 2.2 },
  });
  const [cx, cy, d] = PEN.dot;
  slide.addShape(pptx.ShapeType.ellipse, {
    x: px(cx - d / 2), y: px(cy - d / 2), w: px(d), h: px(d),
    fill: { color: "333333" }, line: { type: "none" },
  });
}

function drawWeightLabel(pptx, slide) {
  slide.addText("Weight", {
    x: px(WEIGHT.cx - 28), y: px(WEIGHT.cy - 7.5), w: px(56), h: px(15),
    rotate: 270, align: "center", valign: "middle", margin: 0,
    fontSize: WEIGHT.size, bold: true, color: C.RED, fontFace: "Times New Roman",
    charSpacing: WEIGHT.charSpacing,
  });
}

// ---- composition ------------------------------------------------------------
function renderSlide(pptx, slide) {
  // house chrome ONCE (numeral = printed number on THIS frame = 5)
  drawHouseChrome(pptx, slide, { numeral: 5 });
  // inherited certified parent blocks (selective per-block composition)
  parent.drawChartFrame(pptx, slide);
  parent.drawAxes(pptx, slide);
  // delta: regression line under the markers
  drawRegressionLine(pptx, slide);
  drawPurpleDelta(pptx, slide);
  parent.drawDataDots(pptx, slide); // 21 dots — identical centers to parent
  drawWeightLabel(pptx, slide);
  parent.drawTitle(pptx, slide);
  drawModelBoxA(pptx, slide);
  drawModelLineBox(pptx, slide);
  parent.drawLengthLabel(pptx, slide);
  drawPenGlyph(pptx, slide);
}

// ---- build ----------------------------------------------------------------
function build(outPath) {
  const pptx = new pptxgen();
  pptx.layout = "LAYOUT_WIDE";
  pptx.author = "slide-recreation";
  pptx.title = "Regression \u2013 One Dimensional Case";
  const slide = pptx.addSlide();
  renderSlide(pptx, slide);
  return pptx.writeFile({ fileName: outPath }).then(() => console.log("written:", outPath));
}

if (require.main === module) {
  const out = process.argv[2] ||
    path.resolve(__dirname, "../slide_005_recreated.pptx");
  build(out).catch((e) => { console.error(e); process.exit(1); });
}

module.exports = { renderSlide, drawRegressionLine, drawPurpleDelta, drawModelBoxA, drawModelLineBox, drawPenGlyph, drawWeightLabel };
