const BORDER = "000000";

function px(v) { return v / 72; }

function drawBoxes(pptx, slide) {
  const boxes = [
    { x: 72, y: 100, w: 92, h: 114, fill: AQUA, lw: 0.75, lc: BORDER },   // y-vec
    { x: 180, y: 100, w: 207, h: 114, fill: AQUA, lw: 0.75, lc: BORDER }, // Z
    { x: 419, y: 100, w: 220, h: 114, fill: AQUA, lw: 0.75, lc: BORDER }, // Z^T
    { x: 688, y: 99, w: 186, h: 113, fill: AQUA, lw: 0.75, lc: BORDER },  // Z^T Z
    { x: 72, y: 233, w: 332, h: 98, fill: AQUA, lw: 0.75, lc: BORDER },   // (Z^T Z)^-1
    { x: 453, y: 235, w: 325, h: 97, fill: MINT, lw: 0.75, lc: BORDER },  // W formula
    { x: 792, y: 235, w: 91, h: 95, fill: AQUA, lw: 0.75, lc: BORDER },   // X
    { x: 74, y: 347, w: 91, h: 33, fill: AQUA, lw: 1.75, lc: NAVY },      // y = W^T X (blue box)
    { x: 214, y: 348, w: 177, h: 34, fill: PALEYEL, lw: 0.75, lc: "CCCC99" }, // highlight
    { x: 436, y: 357, w: 350, h: 176, fill: "FFFFFF", lw: 0.75, lc: BORDER }, // check panel
  ];
  for (const b of boxes) {
    slide.addShape(pptx.ShapeType.rect, {
      x: px(b.x), y: px(b.y), w: px(b.w), h: px(b.h),
      fill: { color: b.fill }, line: { color: b.lc, width: b.lw },
    });
  }
}

function drawImages(slide) {
  for (const s of sidecars) {
    slide.addImage({
      path: path.join(__dirname, "assets", "slide034_eq5", s.name + ".png"),
      x: px(s.x0), y: px(s.y0), w: px(s.w), h: px(s.h),
    });
  }
}

// hollow block-right-arrow outline from a vertex path (points in px)
function arrowOutline(pptx, slide, pts) {
  const lw = 1.25;
  for (let i = 0; i < pts.length - 1; i++) {
    const [x1, y1] = pts[i], [x2, y2] = pts[i + 1];
    const x = Math.min(x1, x2), y = Math.min(y1, y2);
    const w = Math.abs(x2 - x1), h = Math.abs(y2 - y1);
    const flipH = x2 < x1, flipV = y2 < y1;
    slide.addShape(pptx.ShapeType.line, {
      x: px(x), y: px(y), w: px(w), h: px(h),
      line: { color: PINK, width: lw }, flipH, flipV,
    });
  }
}

